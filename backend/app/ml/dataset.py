def _fill(template: str, rng: random.Random, ward: str, bare: float = 0.0) -> str:
    loc = rng.choice(LANDMARKS) + (f" in {ward}" if rng.random() < 0.7 else "")
    if rng.random() < bare:  # short complaint: no location, greeting or sign-off
        return " ".join(template.format(loc="", dur="").replace(" ,", ",").split())
    text = template.format(loc=loc, dur=rng.choice(DURATIONS))
    text = rng.choice(OPENERS) + text.strip() + "." + rng.choice(CLOSERS)
    return " ".join(text.split())


def _fill_dev(template: str, rng: random.Random, ward: str, parts: dict, bare: float = 0.0) -> str:
    loc = rng.choice(parts["landmarks"])
    if rng.random() < 0.7:
        loc = parts["in_ward"].format(ward=WARD_NAMES_DEVANAGARI[ward], loc=loc)
    if rng.random() < bare:
        return " ".join(template.format(loc="", dur="").replace(" ,", ",").split())
    text = template.format(loc=loc, dur=rng.choice(parts["durations"]))
    text = rng.choice(parts["openers"]) + text.strip() + parts["stop"] + rng.choice(parts["closers"])
    return " ".join(text.split())


def generate_training(n_per_class: int = 400, seed: int = 7, n_devanagari: int = 80):
    """n_per_class English + Hinglish rows and n_devanagari Hindi + n_devanagari Marathi rows per category."""
    rng = random.Random(seed)
    rows = []
    for cat, temps in T.items():
        temps = temps + EXTRA[cat]
        for _ in range(n_per_class):
            ward = rng.choice(list(WARDS))
            rows.append((_fill(rng.choice(temps), rng, ward, bare=0.35), cat))
    drng = random.Random(seed + 1)  # separate stream: the rows above stay exactly as they were
    for cat in T:
        for temps, parts in ((HI[cat], HI_PARTS), (MR[cat], MR_PARTS)):
            for _ in range(n_devanagari):
                rows.append((_fill_dev(drng.choice(temps), drng, drng.choice(list(WARDS)), parts, bare=0.35), cat))
    rng.shuffle(rows)
    return rows


def generate_history(n: int = 420, seed: int = 11):
    """Historical grievances with ward, timestamps and resolution info."""
    rng = random.Random(seed)
    cats = list(T)
    weights = [14, 12, 10, 13, 10, 8, 6, 5, 5, 4, 5]
    out = []
    for _ in range(n):
        cat = rng.choices(cats, weights)[0]
        ward = rng.choice(list(WARDS))
        # simulate an emerging hotspot: drainage + health issues in Hadapsar recently
        out.append({"category": cat, "ward": ward,
                    "text": _fill(rng.choice(T[cat]), rng, ward),
                    "resolution": rng.choice(RESOLUTION_NOTES[cat])})
    for text, cat, ward in CRITICAL_SAMPLES:
        out.append({"category": cat, "ward": ward, "text": text, "resolution": rng.choice(RESOLUTION_NOTES[cat]), "recent": True})
