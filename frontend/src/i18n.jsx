export function useLang() {
  const [lang, setLang] = useState(() => (localStorage.getItem('lang') in LANGS ? localStorage.getItem('lang') : 'en'))
  return [lang, STR[lang], (l) => { localStorage.setItem('lang', l); setLang(l) }]
}

export const LangSwitch = ({ lang, onChange }) => (
  <div className="lang-switch">
    {Object.entries(LANGS).map(([k, v]) => <button key={k} type="button" className={k === lang ? 'on' : ''} onClick={() => onChange(k)}>{v.label}</button>)}
  </div>
)
